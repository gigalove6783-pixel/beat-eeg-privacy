"""Slim ladder reports (scripts/audit_slim_reports.py, docs/plan_v3.md §5 A10): `beat-audit
compare` on the tracked `report.slim.json` files writes the committed comparison tables, refuses a
slim report with a changed population or condition as it refuses the full one, and a slim report
holds no per-user or curve-level field."""

import importlib.util
import json
import subprocess
import sys
from pathlib import Path

import pytest

from beat_audit.io import digest

ROOT = Path(__file__).resolve().parents[1]
AUDIT = ROOT / "results" / "audit"
TABLES = [f"ladder_compare_{cohort}{suffix}" for cohort in ("yang2025", "lee2019", "bnci2014_001")
          for suffix in ("", "_calibration_day")]
HEAVY = {"per_user_auc", "partner_auc", "training", "metrics", "operating_points", "histogram",
         "sequential", "closed_set", "gallery", "per_user", "values", "fpr", "fnmr"}
PAIR = AUDIT / "ladder" / "bnci2014_001" / "principal"


@pytest.fixture(scope="module")
def slimmer():
    spec = importlib.util.spec_from_file_location("audit_slim_reports",
                                                  ROOT / "scripts" / "audit_slim_reports.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def compare(args):
    """The tool's own CLI, run from the project root as in the README."""
    return subprocess.run([sys.executable, "-m", "beat_audit", "compare", *map(str, args)],
                          cwd=ROOT, capture_output=True, text=True)


def recorded(table):
    """Arguments of the `compare` call recorded with the committed table."""
    lines = (AUDIT / f"{table}.md").read_text(encoding="utf-8").splitlines()
    return next(line for line in lines
                if line.startswith("python -m beat_audit compare ")).split()[4:]


def lf(data):
    # `compare` ends CSV rows with CRLF (the csv module's default) and the repository stores LF
    # (.gitattributes `* text=auto eol=lf`): a checkout holds the committed tables with LF
    return data.replace(b"\r\n", b"\n")


def keys(value):
    if isinstance(value, dict):
        for key, item in value.items():
            yield key
            yield from keys(item)
    elif isinstance(value, list):
        for item in value:
            yield from keys(item)


@pytest.mark.parametrize("table", TABLES)
def test_compare_on_slim_reports_writes_the_committed_table(table, tmp_path):
    args = recorded(table)
    assert any(a.endswith("/report.json") for a in args)
    args = [a.replace("/report.json", "/report.slim.json") for a in args]
    args[args.index("--out") + 1] = tmp_path / f"{table}.csv"
    done = compare(args)
    assert done.returncode == 0, done.stderr
    assert lf((tmp_path / f"{table}.csv").read_bytes()) == lf((AUDIT / f"{table}.csv").read_bytes())


def stale_population(cell):
    user = cell["population"]["users"][0]
    cell["population"]["folds"][user] = (cell["population"]["folds"][user] + 1) % 3


def population(cell):
    stale_population(cell)
    cell["population_hash"] = digest(cell["population"])


def condition(cell):
    cell["resolved_pairs"] = [[pair[1], pair[0]] for pair in cell["resolved_pairs"]]


SIGNATURE = ("cohort/days/condition A/B selectors/k/population_hash: use reports with the same "
             "resolved physical conditions and analysed population")
REFUSALS = [(None, None),
            (stale_population, "population_hash: analysed users/masks/folds differ; rerun on one "
                               "population"),
            (population, SIGNATURE), (condition, SIGNATURE)]


@pytest.mark.parametrize("name", ["report.slim.json", "report.json"])
@pytest.mark.parametrize("change,refusal", REFUSALS)
def test_a_changed_population_or_condition_is_refused_as_on_the_full_report(
        name, change, refusal, tmp_path):
    features, commands = (PAIR / rung / name for rung in ("features_P0", "commands_shared_tau0.50"))
    if not commands.exists():
        pytest.skip("full reports are not tracked (regenerated by scripts/audit_ladder.py)")
    if change is not None:
        report = json.loads(commands.read_text(encoding="utf-8"))
        change(next(cell for cell in report["cells"] if cell["status"] == "ok"))
        commands = tmp_path / name
        commands.write_text(json.dumps(report), encoding="utf-8")
    done = compare([f"features_P0={features}", f"commands_shared_tau0.50={commands}",
                    "--utility", AUDIT / "ladder_compare_bnci2014_001_utility.json",
                    "--out", tmp_path / "pair.csv"])
    if refusal is None:
        assert done.returncode == 0, done.stderr
    else:
        assert (done.returncode, done.stderr.strip()) == (2, f"beat-audit: {refusal}")


def test_every_compared_rung_has_a_slim_report_without_per_user_fields():
    compared = {ROOT / a.split("=", 1)[1].replace("/report.json", "/report.slim.json")
                for table in TABLES for a in recorded(table) if a.endswith("/report.json")}
    assert sorted(compared) == sorted((AUDIT / "ladder").glob("*/*/*/report.slim.json"))
    assert len(compared) == 41
    for path in compared:
        data = path.read_bytes()
        assert b"\r" not in data and data.endswith(b"\n")
        report = json.loads(data)
        # configuration.settings keeps the switches named sequential, closed_set and gallery
        assert not HEAVY & set(keys([report[field] for field in
                                     ("cells", "unavailable_analyses", "contrasts")]))
        assert report["slim"]["derived_from"]["file"] == "report.json"
        assert {"cells[].comparators.<comparator>.per_user_auc",
                "cells[].comparators.<comparator>.partner_auc"} <= set(report["slim"]["removed"])


def test_slim_reports_are_derived_deterministically_from_their_full_reports(slimmer):
    full = sorted((AUDIT / "ladder" / "bnci2014_001").glob("*/*/report.json"))
    if not full:
        pytest.skip("full reports are not tracked (regenerated by scripts/audit_ladder.py)")
    for path in full:
        first = slimmer.slim(path)
        assert first == slimmer.slim(path)
        tracked = json.loads(path.with_name("report.slim.json").read_bytes())
        assert tracked == first
        report = json.loads(path.read_bytes())
        assert first["slim"]["derived_from"]["bytes"] == path.stat().st_size
        for kept, original in zip(first["cells"], report["cells"]):
            assert {k: v for k, v in original.items() if k != "comparators"} == {
                k: v for k, v in kept.items() if k != "comparators"}
            for comparator, result in kept["comparators"].items():
                assert result.items() <= original["comparators"][comparator].items()
